namespace MasterInterface.Interfaces
{
    /// <summary>
    /// Интерфейс для отправки команд к мастеру/устройству и получения ответов.
    /// </summary>
    /// <remarks>
    /// Реализации должны предоставлять асинхронные операции отправки команд.
    /// Методы не должны блокировать вызывающий поток. Для множественных команд
    /// порядок ответов в возвращаемом массиве должен соответствовать порядку
    /// переданных команд.
    /// </remarks>
    public interface ICommandSender : IMasterInterface
    {
        /// <summary>
        /// Устанавливает функцию-исполнитель для отправки одиночной команды.
        /// </summary>
        /// <param name="executeCommand">
        /// Делегат, принимающий текст команды и возвращающий <see cref="Task{String}"/>
        /// с ответом устройства. Если передается <c>null</c>, текущий исполнитель должен быть снят/очищен
        /// (реализация может трактовать это как сброс в состояние по умолчанию).
        /// </param>
        /// <remarks>
        /// Этот метод используется для внедрения конкретной логики отправки команд (напр., тестовый мок,
        /// адаптер к разному каналу связи). Делегат должен быть асинхронным и не блокировать поток.
        /// </remarks>
        void SetCommandExecutor(Func<string, Task<string>> executeCommand);

        /// <summary>
        /// Асинхронно отправляет одну команду и возвращает ответ в виде строки.
        /// </summary>
        /// <param name="command">Текст команды для отправки. Не должен быть <c>null</c>.</param>
        /// <returns>
        /// Задача, представляющая асинхронную операцию. Результат — строка с ответом мастера/устройства.
        /// </returns>
        /// <exception cref="System.ArgumentNullException">
        /// Выбрасывается, если <paramref name="command"/> равен <c>null</c> (по соглашению реализации).
        /// </exception>
        Task<string> SendCommandAsync(string command);
    }
}
